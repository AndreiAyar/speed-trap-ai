// API client helpers centralize HTTP calls for dashboard components.

// We define API base URL with env override for flexibility.
const API_BASE = import.meta.env.VITE_API_BASE_URL ?? "http://localhost:8787/api";

// We define artifact base URL served by API static route.
const ARTIFACT_BASE = (import.meta.env.VITE_ARTIFACT_BASE_URL ?? "http://localhost:8787/artifacts").replace(/\/$/, "");

// Type for create job request payload.
export interface CreateJobPayload {
  // MVP currently supports file source.
  sourceType: "file";
  // Absolute or workspace-relative path to input video.
  sourcePath: string;
  // Optional config id for future multi-scene support.
  cameraConfigId?: string;
}

// Type for create job response.
export interface CreateJobResponse {
  // Job id generated by API.
  jobId: string;
  // Initial status (usually queued).
  status: "queued" | "running" | "done" | "failed";
}

// Type for job status payload.
export interface JobResponse {
  // Job identifier.
  id: string;
  // Current lifecycle status.
  status: "queued" | "running" | "done" | "failed";
  // Current progress in percent.
  progress: number;
  // Original source path.
  sourcePath: string;
  // Artifact absolute paths from backend.
  artifacts: {
    overlayVideo?: string;
    summaryCsv?: string;
    eventsJsonl?: string;
    metadataJson?: string;
  };
  // Optional failure text.
  errorMessage?: string;
  // Timestamp when job was created.
  createdAt: string;
  // Optional timestamp when job finished or failed.
  finishedAt?: string;
}

// Type for recent jobs list payload.
export interface JobsListResponse {
  // Recent jobs from newest to oldest.
  jobs: JobResponse[];
  // Number of jobs returned.
  count: number;
}

// Type for one vehicle row.
export interface VehicleTrack {
  // Tracker id for this vehicle.
  trackId: number;
  // Detector class id.
  classId: number;
  // Maximum estimated speed in km/h.
  maxSpeedKmh: number | null;
  // Average estimated speed in km/h.
  avgSpeedKmh: number | null;
  // Timestamp when track first appeared.
  firstSeenMs: number;
  // Timestamp when track last appeared.
  lastSeenMs: number;
  // Timestamp for line A crossing.
  crossedAms: number | null;
  // Timestamp for line B crossing.
  crossedBms: number | null;
  // Number of samples captured.
  numSamples: number;
}

// Type for list endpoint payload.
export interface VehiclesResponse {
  // Parent job id.
  jobId: string;
  // Sorted tracks array.
  tracks: VehicleTrack[];
  // Active sort key.
  sort: string;
  // Active sort order.
  order: "asc" | "desc";
}

// This helper checks fetch responses and throws readable errors.
async function parseJsonOrThrow<T>(res: Response): Promise<T> {
  // We parse response body as JSON.
  const data = await res.json();

  // We throw API-provided error when response failed.
  if (!res.ok) {
    throw new Error((data as { error?: string }).error ?? "API request failed.");
  }

  // We return typed parsed payload.
  return data as T;
}

// API call: create processing job.
export async function createJob(payload: CreateJobPayload): Promise<CreateJobResponse> {
  const res = await fetch(`${API_BASE}/jobs`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload),
  });
  return parseJsonOrThrow<CreateJobResponse>(res);
}

// API call: fetch one job state.
export async function getJob(jobId: string): Promise<JobResponse> {
  const res = await fetch(`${API_BASE}/jobs/${jobId}`);
  return parseJsonOrThrow<JobResponse>(res);
}

// API call: fetch recent jobs for history panel and refresh recovery.
export async function getJobs(limit: number = 30): Promise<JobsListResponse> {
  const res = await fetch(`${API_BASE}/jobs?limit=${encodeURIComponent(String(limit))}`);
  return parseJsonOrThrow<JobsListResponse>(res);
}

// API call: delete one job and remove its generated artifacts.
export async function deleteJob(jobId: string): Promise<{ deletedJobId: string; removedOutputDir: boolean }> {
  const res = await fetch(`${API_BASE}/jobs/${jobId}`, {
    method: "DELETE",
  });
  return parseJsonOrThrow<{ deletedJobId: string; removedOutputDir: boolean }>(res);
}

// API call: fetch vehicle leaderboard.
export async function getVehicles(jobId: string, sort: string = "maxSpeedKmh", order: "asc" | "desc" = "desc"): Promise<VehiclesResponse> {
  const url = `${API_BASE}/jobs/${jobId}/vehicles?sort=${encodeURIComponent(sort)}&order=${encodeURIComponent(order)}`;
  const res = await fetch(url);
  return parseJsonOrThrow<VehiclesResponse>(res);
}

// API call: fetch one vehicle details.
export async function getVehicle(jobId: string, trackId: number): Promise<{ track: VehicleTrack; notes: Record<string, string> }> {
  const res = await fetch(`${API_BASE}/jobs/${jobId}/vehicles/${trackId}`);
  return parseJsonOrThrow<{ track: VehicleTrack; notes: Record<string, string> }>(res);
}

// Helper converts absolute artifact path to API static URL.
export function toArtifactUrl(absolutePath: string): string {
  // We normalize path separators for browser URLs.
  const normalizedPath = absolutePath.replace(/\\/g, "/");

  // We extract path segment after /data/output/ for static serving.
  const marker = "/data/output/";
  const markerIndex = normalizedPath.indexOf(marker);

  // If marker is missing, we return empty URL to avoid broken links.
  if (markerIndex < 0) {
    return "";
  }

  // We build relative artifact path for server static route.
  const relative = normalizedPath.slice(markerIndex + marker.length);

  // We return final public URL.
  return `${ARTIFACT_BASE}/${relative}`;
}
